#!/usr/bin/env python3
"""Mark an existing image page as the EPUB cover, without changing page images."""
import argparse,datetime,hashlib,os,zipfile
from pathlib import Path
from xml.etree import ElementTree as E
from audit_epub import audit
NS='http://www.idpf.org/2007/opf'
E.register_namespace('',NS)
E.register_namespace('dc','http://purl.org/dc/elements/1.1/')
def set_cover(source,output,page):
 source=Path(source);output=Path(output)
 if output.exists():raise FileExistsError(output)
 if page<1:raise ValueError('page must be positive')
 output.parent.mkdir(parents=True,exist_ok=True);tmp=output.with_name(output.name+'.partial')
 with zipfile.ZipFile(source) as src,zipfile.ZipFile(tmp,'w') as dst:
  root=E.fromstring(src.read('OEBPS/content.opf'));manifest=root.find('{'+NS+'}manifest');meta=root.find('{'+NS+'}metadata')
  pagehref=f'p{page}.xhtml';pageitem=next((x for x in manifest if x.get('href')==pagehref),None)
  if pageitem is None:raise ValueError('Expected page-per-file EPUB generated by this skill')
  pagexml=E.fromstring(src.read('OEBPS/'+pagehref));img=pagexml.find('.//{http://www.w3.org/1999/xhtml}img')
  if img is None:raise ValueError('Cover page has no image')
  cover=next(x for x in manifest if x.get('href')==img.get('src'))
  for x in manifest:
   props=x.get('properties','').split();props=[p for p in props if p!='cover-image']
   if x is cover:props.append('cover-image')
   if props:x.set('properties',' '.join(props))
   else:x.attrib.pop('properties',None)
  for x in list(meta):
   if x.get('name')=='cover':meta.remove(x)
  E.SubElement(meta,'{'+NS+'}meta',{'name':'cover','content':cover.get('id')})
  modified=meta.find('{'+NS+'}meta[@property="dcterms:modified"]')
  if modified is not None:modified.text=datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
  guide=root.find('{'+NS+'}guide')
  if guide is None:guide=E.SubElement(root,'{'+NS+'}guide')
  for x in list(guide):
   if x.get('type')=='cover':guide.remove(x)
  E.SubElement(guide,'{'+NS+'}reference',{'type':'cover','title':'Cover','href':pagehref})
  before={}
  for info in src.infolist():
   data=src.read(info.filename)
   if info.filename.startswith('OEBPS/images/'):before[info.filename]=hashlib.sha256(data).hexdigest()
   if info.filename=='OEBPS/content.opf':data=E.tostring(root,encoding='utf-8',xml_declaration=True)
   dst.writestr(info,data)
 result=audit(tmp)
 if result['errors']:raise ValueError(result['errors'])
 with zipfile.ZipFile(tmp) as z:
  if any(hashlib.sha256(z.read(n)).hexdigest()!=h for n,h in before.items()):raise ValueError('Image changed')
 os.replace(tmp,output)
 return {'output':str(output),'cover_page':page,'unchanged_images':len(before)}
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('input');p.add_argument('output');p.add_argument('--page',type=int,required=True);a=p.parse_args();print(set_cover(a.input,a.output,a.page))
